test('templates: 11 styles, 16 finite steps per class, plausible ranges, attribution', () => {
  assert.deepEqual([...GROOVE_IDS], ['hiphop', 'funk', 'soul', 'jazz', 'shuffle', 'latin', 'reggae', 'afrobeat', 'rock', 'pop', 'dance']);
  assert.equal(new Set(GROOVE_IDS).size, GROOVE_IDS.length);
  for (const t of GROOVE_TEMPLATES) {
    assert.ok(t.performances >= 4, `${t.id}: ${t.performances} performances`);
    assert.ok(t.drummers >= 2 && t.bars >= 200, t.id);
    assert.ok(t.label.length > 2 && t.styles.length >= 1, t.id);
    assert.ok(t.bpm[0] <= t.bpm[1] && t.bpm[1] <= t.bpm[2], t.id);
    assert.ok(t.swing8 >= 0.45 && t.swing8 <= 0.72 && t.swing16 >= 0.4 && t.swing16 <= 0.72, `${t.id} swing ${t.swing8}/${t.swing16}`);
    for (const c of GROOVE_CLASSES) {
      const k = t.classes[c];
      for (const [name, arr] of Object.entries(k)) {
        assert.equal(arr.length, 16, `${t.id}.${c}.${name}`);
        for (const v of arr) assert.ok(Number.isFinite(v), `${t.id}.${c}.${name} has ${v}`);
      }
      assert.ok(k.offset.every((v) => Math.abs(v) < 0.75), `${t.id}.${c} offsets stay under ¾ of a 16th`);
      assert.ok(k.spread.every((v) => v >= 0) && k.vel.every((v) => v > 0.2 && v < 3) && k.prob.every((v) => v >= 0 && v <= 1), `${t.id}.${c}`);
      assert.ok(k.n.every((v) => Number.isInteger(v) && v >= 0), `${t.id}.${c}.n`);
      const w = k.prob.reduce((a, b) => a + b, 0);
      if (w > 0.2) {
        const mean = k.vel.reduce((a, v, s) => a + v * k.prob[s], 0) / w;
        assert.ok(Math.abs(mean - 1) < 0.03, `${t.id}.${c} accents average to 1 (got ${mean})`);
      }
    }
  }
  const total = GROOVE_TEMPLATES.reduce((a, t) => a + t.performances, 0);
  assert.ok(total >= 400 && total <= 503, `${total} performances in total (GMD has 503 4/4 beats)`);
  assert.equal(GROOVE_ATTRIBUTION, 'Derived from the Groove MIDI Dataset by Google LLC (Magenta), CC BY 4.0');
  const src = fs.readFileSync(path.join(ROOT, 'shared', 'grooves', 'templates.gen.ts'), 'utf8');
  assert.match(src, /^\/\/ GENERATED by scripts\/grooves\/extract\.mjs/);
  assert.ok(src.includes('Derived from the Groove MIDI Dataset by Google LLC (Magenta), CC BY 4.0'));
  for (const t of GROOVE_TEMPLATES) assert.match(src, new RegExp(`//\\s+${t.id}\\s+${t.performances}\\s`), `${t.id} count in the header`);
});

test('templates: the measurements look like the styles they claim to be', () => {
  const rock = findGroove('rock')!;
  assert.ok(rock.classes.kick.prob[0] > 0.6, 'rock: kick on the one');
  assert.ok(rock.classes.snare.prob[4] > 0.5 && rock.classes.snare.prob[12] > 0.5, 'rock: backbeat on 2 and 4');
  assert.ok(rock.swing8 < 0.53, 'rock is straight');
  const shuffle = findGroove('shuffle')!;
  assert.ok(shuffle.swing8 > 0.58, `shuffle swings its 8ths (${shuffle.swing8})`);
  assert.ok(shuffle.classes.hihat.offset[2] > 0.25, 'shuffle: the off-8th hat is late');
  for (const t of GROOVE_TEMPLATES) {
    const h = t.classes.hihat;
    assert.ok(h.vel[0] + h.vel[4] + h.vel[8] + h.vel[12] > h.vel[1] + h.vel[5] + h.vel[9] + h.vel[13], `${t.id} hat accents`);
  }
});

