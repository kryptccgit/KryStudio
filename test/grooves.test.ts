function grid(n: number, vel = 100 / 127): GrooveNote[] {
  return Array.from({ length: n }, (_, i) => ({ tick: i * SIX, dur: SIX / 2, vel }));
}

test('applyGroove: amount 0 + velocity 0 is the identity; deterministic; on-grid notes move by the template offset', () => {
  const notes = grid(32);
  const same = applyGroove(notes, { template: 'funk', amount: 0, velocity: 0, class: 'hihat' });
  assert.deepEqual(same, notes);
  assert.ok(same.every((n, i) => n === notes[i]), 'unchanged notes are returned as-is');
  const a = applyGroove(notes, { template: 'hiphop', amount: 1, velocity: 0.7, channelName: 'Kick', length: 32 * SIX });
  const b = applyGroove(notes, { template: 'hiphop', amount: 1, velocity: 0.7, channelName: 'Kick', length: 32 * SIX });
  assert.deepEqual(a, b);
  const kick = findGroove('hiphop')!.classes.kick;
  a.forEach((n, i) => {
    const want = Math.max(0, Math.round(i * SIX + kick.offset[i % 16] * SIX));
    assert.equal(n.tick, want, `step ${i}`);
    assert.equal(n.dur, SIX / 2);
  });
  const half = applyGroove(notes, { template: 'shuffle', amount: 0.5, velocity: 0, class: 'hihat' });
  const full = applyGroove(notes, { template: 'shuffle', amount: 1, velocity: 0, class: 'hihat' });
  half.forEach((n, i) => assert.ok(Math.abs(n.tick - notes[i].tick - (full[i].tick - notes[i].tick) / 2) <= 1, `half shift at ${i}`));
  assert.deepEqual(applyGroove(notes, { template: 'jazz', class: 'snare' }), applyGroove(notes, { template: 'jazz', channelName: 'Clap' }));
  assert.equal(notes[1].tick, SIX);
  assert.throws(() => applyGroove(notes, { template: 'nope' }), /Unknown groove "nope" \(use one of: hiphop/);
});

test('applyGroove: re-applying does not push notes further; velocities shape by step', () => {
  const notes = grid(16);
  for (const id of GROOVE_IDS) {
    for (const cls of GROOVE_CLASSES) {
      const once = applyGroove(notes, { template: id, amount: 1, velocity: 0, class: cls });
      const twice = applyGroove(once, { template: id, amount: 1, velocity: 0, class: cls });
      assert.deepEqual(twice.map((n) => n.tick), once.map((n) => n.tick), `${id}.${cls}`);
    }
  }
  const t = findGroove('rock')!;
  const v = applyGroove(notes, { template: t, amount: 0, velocity: 1, class: 'hihat' });
  v.forEach((n, i) => assert.ok(Math.abs(n.vel - Math.min(1, (100 / 127) * t.classes.hihat.vel[i])) < 0.002, `vel at ${i}`));
});

test('applyGroove: notes stay inside the pattern and velocities inside MIDI 1..127', () => {
  const len = 4 * 16 * SIX;
  const rnd = seededRandom(42);
  const notes: GrooveNote[] = [];
  for (let i = 0; i < 400; i++) {
    const tick = i < 2 ? [0, len - 1][i] : Math.floor(rnd() * len);
    notes.push({ tick, dur: 1 + Math.floor(rnd() * (len - tick - 1 > 0 ? Math.min(960, len - tick) : 1)), vel: i % 3 === 0 ? 1 : i % 3 === 1 ? 0 : rnd() });
  }
  for (const id of GROOVE_IDS) {
    for (const cls of GROOVE_CLASSES) {
      const out = applyGroove(notes, { template: id, amount: 1, velocity: 1, class: cls, length: len });
      out.forEach((n, i) => {
        assert.ok(n.tick >= 0 && n.tick < len, `${id}.${cls}: tick ${n.tick}`);
        if (notes[i].tick + notes[i].dur <= len) assert.ok(n.tick + n.dur <= len, `${id}.${cls}: end ${n.tick + n.dur}`);
        assert.ok(n.dur >= 1 && Number.isInteger(n.tick) && Number.isInteger(n.dur));
        const midi = Math.round(n.vel * 127);
        assert.ok(midi >= 1 && midi <= 127 && n.vel <= 1, `${id}.${cls}: vel ${n.vel}`);
      });
    }
  }
  const k = findGroove('pop')!.classes.kick;
  const waltz = applyGroove([{ tick: 12 * SIX, dur: 10, vel: 0.5 }], { template: 'pop', class: 'kick', velocity: 0, stepsPerBar: 12 });
  assert.equal(waltz[0].tick, Math.round(12 * SIX + k.offset[0] * SIX));
});

function doc() {
  const p = createDefaultProject('Grooves');
  const host = new DocHost(p, CATALOG, { strict: true });
  const pat = p.transport.activePatternId!;
  const id = (name: string) => p.channelOrder.find((c) => p.channels[c].name === name)!;
  return { host, pat, id };
}

test('notes.groove: one undo step, class from the channel name, clear errors', () => {
  const { host, pat, id } = doc();
  const hat = id('Hat');
  const r0 = host.exec<{ ids: string[] }>('notes.replace', { patternId: pat, channelId: hat, notes: grid(16).map((n) => ({ ...n, key: 60 })) }, { actor: USER });
  assert.equal(r0.ok, true, r0.message);
  const list = (ch: string): Note[] => Object.values(host.project.patterns[pat].notes[ch] ?? {}).sort((a, b) => a.tick - b.tick);
  const before = list(hat).map((n) => [n.tick, n.vel]);
  const h0 = host.getHistory().length;
  const r = host.exec<{ changed: number; instrument: string; template: string }>('notes.groove', { patternId: pat, channelId: hat, template: 'Hip hop' }, { actor: USER });
  assert.equal(r.ok, true, r.message);
  assert.equal(r.data!.instrument, 'hihat');
  assert.equal(r.data!.template, 'hiphop');
  assert.equal(host.getHistory().length, h0 + 1, 'one undo step');
  const want = applyGroove(grid(16), { template: 'hiphop', class: 'hihat', amount: 1, velocity: 0.5, length: 16 * SIX });
  assert.deepEqual(list(hat).map((n) => [n.tick, n.vel]), want.map((n) => [n.tick, n.vel]));

  const again = host.exec('notes.groove', { patternId: pat, channelId: hat, template: 'hiphop', velocity: 0 }, { actor: USER });
  assert.equal(again.ok, false);
  assert.match(again.message!, /No change/);
  assert.equal(host.undo(USER).ok, true);
  assert.deepEqual(list(hat).map((n) => [n.tick, n.vel]), before);

  const bad = host.exec('notes.groove', { patternId: pat, channelId: hat, template: 'polka' }, { actor: USER });
  assert.equal(bad.ok, false);
  assert.match(bad.message!, /Unknown groove "polka" \(use one of: hiphop, funk/);
  const zero = host.exec('notes.groove', { patternId: pat, channelId: hat, template: 'funk', amount: 0, velocity: 0 }, { actor: USER });
  assert.match(zero.message!, /Nothing to apply/);
  const missing = host.exec('notes.groove', { patternId: pat, channelId: hat, template: 'funk', ids: ['n_missing'] }, { actor: USER });
  assert.match(missing.message!, /not found/);
  const empty = host.exec('notes.groove', { patternId: pat, channelId: id('Keys'), template: 'funk' }, { actor: USER });
  assert.match(empty.message!, /No notes to groove/);

  const keys = id('Keys');
  host.exec('notes.replace', { patternId: pat, channelId: keys, notes: grid(16).map((n) => ({ ...n, key: 60 })) }, { actor: USER });
  const k = host.exec<{ instrument: string }>('notes.groove', { patternId: pat, channelId: keys, template: 'funk', instrument: 'kick', velocity: 0 }, { actor: USER });
  assert.equal(k.data!.instrument, 'kick');
  const wantKick = applyGroove(grid(16), { template: 'funk', class: 'kick', velocity: 0, length: 16 * SIX });
  assert.deepEqual(list(keys).map((n) => n.tick), wantKick.map((n) => n.tick));
});

function mcp() {
  const d = doc();
  const deps = {
    doc: d.host,
    broadcast: () => {},
    log: () => {},
    getSettings: () => ({ mcp: { enabled: true, httpEnabled: false, httpPort: 47800, requireConsentForDestructive: false } }),
  } as unknown as MainDeps;
  const caller: ToolCaller = { actor: { kind: 'agent', clientId: 'test-agent', name: 'Test Agent' }, session: newSession(), via: 'test' };
  return { ...d, call: (name: string, args: unknown) => callTool(deps, caller, name, args) };
}

test('transform_notes groove op: lists the templates, grooves drums by name, chains with other ops', async () => {
  const tool = TOOLS.find((t) => t.name === 'transform_notes')!;
  for (const id of GROOVE_IDS) assert.ok(tool.description.includes(id), `description lists ${id}`);
  assert.ok(JSON.stringify(inputJsonSchema(tool)).includes('"shuffle"'), 'template is an enum in the JSON schema');

  const { host, pat, id, call } = mcp();
  const snare = id('Snare');
  host.exec('notes.replace', { patternId: pat, channelId: snare, notes: [4, 12, 20, 28].map((s) => ({ tick: s * SIX, dur: 120, key: 60, vel: 0.8 })) }, { actor: USER });
  const r = await call('transform_notes', { channel: 'Snare', ops: [{ op: 'groove', template: 'shuffle', velocity: 0 }] });
  assert.equal(r.ok, true, r.message);
  assert.match(r.message, /groove shuffle/);
  const sn = findGroove('shuffle')!.classes.snare;
  const ticks = Object.values(host.project.patterns[pat].notes[snare]).map((n) => n.tick).sort((a, b) => a - b);
  assert.deepEqual(ticks, [4, 12, 20, 28].map((s) => Math.round(s * SIX + sn.offset[s % 16] * SIX)));

  const r2 = await call('transform_notes', { channel: 'Snare', ops: [{ op: 'velocity', set: 100 }, { op: 'groove', template: 'funk', amount: 0, velocity: 1 }] });
  assert.equal(r2.ok, true, r2.message);
  const fv = findGroove('funk')!.classes.snare.vel;
  const vels = Object.values(host.project.patterns[pat].notes[snare]).sort((a, b) => a.tick - b.tick).map((n) => n.vel);
  vels.forEach((v, i) => assert.ok(Math.abs(v - Math.min(1, (100 / 127) * fv[[4, 12, 4, 12][i]])) < 0.002, `accent ${i}`));

  const bad = await call('transform_notes', { channel: 'Snare', ops: [{ op: 'groove', template: 'polka' }] });
  assert.equal(bad.ok, false);
});

