function ep(o: { gain: number; body: number; tine: number; tineDecay?: number; bodyDecay?: number; cutoff?: number }): ReturnType<typeof fm> {
  const ops: [Op, Op, Op, Op] = [
    { ratio: 1, level: 0.85, vel: 0.7, a: 1, d: o.bodyDecay ?? 4500, s: 0, r: 500 },
    { ratio: 1, level: o.body, vel: 0.9, a: 1, d: 1800, s: 0.15, r: 400 },
    { ratio: 1, level: 0.6, detune: 3, vel: 0.9, a: 0.5, d: 1500, s: 0, r: 300 },
    { ratio: 14, level: o.tine, vel: 1, a: 0.1, d: o.tineDecay ?? 220, s: 0, r: 200 },
  ];
  return fm({ gain: o.gain, algorithm: ALG.pairs, ops, ...(o.cutoff ? { cutoff: o.cutoff, filterKeyTrack: 0.4 } : {}) });
}

