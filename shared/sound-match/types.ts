// ──────────────────────────────────────────────────────────────────────
// Sound matching (research/15-closer-to-reference.md §2): a timbre
// "fingerprint" of a sound, measured by the analyzer (`fingerprint` cmd,
// engine/crates/analyzer), so a part of a reference song (its kick, its
// bass, its lead, read from the separated stems) can be matched to the
// closest factory preset / sample / pack sample, then nudged closer by
// parameter tweaks. Pure data: numbers, never audio.
// ──────────────────────────────────────────────────────────────────────

import type { InstrumentRole, SampleKind } from '../sounds/types';

/**
 * Timbre features of one sound (a whole file or one segment of it). Every field is finite; levels are dBFS-relative
 * so loudness doesn't decide the match (gain is set separately).
 */
export interface SoundFingerprint {
  /** Seconds measured (after trimming leading / trailing silence below -60 dBFS). */
  lengthSec: number;
  /** Spectral centroid (Hz), energy-weighted over the sound. */
  centroidHz: number;
  /** Frequency below which 85% of the energy lies (Hz). */
  rolloffHz: number;
  /** Spectral flatness 0 (pure tone) .. 1 (white noise), energy-weighted. */
  flatness: number;
  /** Harmonic-to-noise estimate 0..1 (how pitched it is). */
  harmonicity: number;
  /** Fundamental (Hz) when pitched and stable enough (harmonicity ≥ 0.4), else null. */
  f0Hz: number | null;
  /** Time from start to peak envelope (ms, 5 ms RMS envelope). */
  attackMs: number;
  /** Time from peak to -20 dB below peak (ms; capped at lengthSec). */
  decayMs: number;
  /** Mean envelope over the second half relative to the peak (0..1): 0 = percussive, ~1 = sustained. */
  sustain: number;
  /** Energy per band relative to the loudest band (dB, ≤ 0): sub <60, low 60-250, lowMid 250-500, mid 500-2k, highMid 2k-6k, high 6k-20k. */
  bands: { sub: number; low: number; lowMid: number; mid: number; highMid: number; high: number };
  /** Peak-to-RMS (dB): transient snap / compression. */
  crestDb: number;
  /** 0 mono .. 1 very wide (side/mid energy ratio, clamped); 0 for mono files. */
  width: number;
  /** Peak level of the measured audio (dBFS): for gain matching, not for similarity. */
  peakDb: number;
  /** RMS level (dBFS). */
  rmsDb: number;
}

/** What a fingerprint in the index belongs to. */
export type FingerprintSource =
  /** An instrument preset rendered by the engine at `note` (shared/sounds/factory). */
  | { kind: 'preset'; id: string; role: InstrumentRole; note: number }
  /** A factory / pack sample file. */
  | { kind: 'sample'; path: string; sampleKind: SampleKind };

export interface FingerprintEntry {
  source: FingerprintSource;
  fp: SoundFingerprint;
}

/**
 * resources/factory/fingerprints.json (GENERATED by scripts/fingerprints.mjs from the engine + analyzer; never
 * hand-edit). Pack samples are fingerprinted on demand and cached in userData/analysis/fingerprints-packs.json with
 * the same entry shape.
 */
export interface FingerprintIndex {
  version: 1;
  /** e.g. "krypt-studio-analyzer 0.1.0 / presets 2026-10-14". */
  generator: string;
  entries: FingerprintEntry[];
}

/** A part of the reference to match a sound for (from the stems). */
export type MatchTarget =
  | { kind: 'drum'; role: 'kick' | 'snare' | 'clap' | 'hat' | 'openhat' | 'perc' }
  | { kind: 'instrument'; role: InstrumentRole };

/** One candidate the matcher proposes, best first. */
export interface SoundMatch {
  source: FingerprintSource;
  /** 0..1, 1 = identical features (weighted per target kind). */
  similarity: number;
  /** Plain reasons ("darker than the reference kick: centroid 180 Hz vs 260 Hz"). */
  why: string[];
  /**
   * Parameter nudges that move the candidate toward the target, in the plugin's own units (set_params style),
   * e.g. { cutoff: 2400, decay: 380 } or for samples { pitch: -2 } (semitones on the channel), gainDb to level-match.
   */
  tweaks: Record<string, number>;
}
