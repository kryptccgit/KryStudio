// Build + stage the plugin-host test plugins (NOT shipped).
//
//   node engine/crates/pluginhost/testplugins/stage.mjs [--out <dir>] [--test]
//
// Produces <out>/CLAP/krypt-test.clap, <out>/VST3/KryptTestGain.vst3 (single
// file) and <out>/VST3/KryptTestGainBundle.vst3/ (bundle with a
// moduleinfo.json, for the scanner's fast path). --test also runs the
// engine-side end-to-end tests against them. Add <out>/CLAP and <out>/VST3
// as folders in the Plugin Manager to try them in the app.
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const here = import.meta.dirname;
const root = path.resolve(here, '..', '..', '..', '..');
const args = process.argv.slice(2);
const outIdx = args.indexOf('--out');
const out = path.resolve(outIdx >= 0 ? args[outIdx + 1] : path.join(root, 'engine', 'target-plug', 'testkit'));
const target = path.join(root, 'engine', 'target-plug');

function run(cmd, argv, env = {}) {
  const r = spawnSync(cmd, argv, { cwd: root, stdio: 'inherit', env: { ...process.env, ...env }, windowsHide: true });
  if (r.status !== 0) {
    console.error(`✖ ${cmd} ${argv.join(' ')} exited with ${r.status}`);
    process.exit(1);
  }
}

run('cargo', ['build', '--manifest-path', path.join(here, 'Cargo.toml'), '--target-dir', path.join(target, 'testplugins')]);
const dbg = path.join(target, 'testplugins', 'debug');
mkdirSync(path.join(out, 'CLAP'), { recursive: true });
mkdirSync(path.join(out, 'VST3'), { recursive: true });
copyFileSync(path.join(dbg, 'krypt_test_clap.dll'), path.join(out, 'CLAP', 'krypt-test.clap'));
copyFileSync(path.join(dbg, 'krypt_test_vst3.dll'), path.join(out, 'VST3', 'KryptTestGain.vst3'));
const bundle = path.join(out, 'VST3', 'KryptTestGainBundle.vst3');
mkdirSync(path.join(bundle, 'Contents', 'x86_64-win'), { recursive: true });
mkdirSync(path.join(bundle, 'Contents', 'Resources'), { recursive: true });
copyFileSync(path.join(dbg, 'krypt_test_vst3.dll'), path.join(bundle, 'Contents', 'x86_64-win', 'KryptTestGainBundle.vst3'));
// JSON5 on purpose (comments + trailing commas), like real SDK output.
writeFileSync(
  path.join(bundle, 'Contents', 'Resources', 'moduleinfo.json'),
  `{
  // generated by stage.mjs
  "Name": "KryptTestGainBundle",
  "Version": "1.0.0",
  "Factory Info": { "Vendor": "Krypt (test)", "URL": "https://krypt.cc", "E-Mail": "", "Flags": { "Unicode": true, }, },
  "Compatibility": [],
  "Classes": [
    { "CID": "5059524B54545345545647334741494E", "Category": "Audio Module Class", "Name": "Krypt Test VST3 Gain",
      "Vendor": "Krypt (test)", "Version": "1.0.0", "SDKVersion": "VST 3.8.1", "Sub Categories": ["Fx", "Tools"],
      "Class Flags": 0, "Cardinality": 2147483647, "Snapshots": [], },
  ],
}
`,
);
console.log(`✔ staged test plugins in ${out}`);

if (args.includes('--test')) {
  run('cargo', ['build', '--manifest-path', path.join(root, 'engine', 'Cargo.toml'), '-p', 'krypt-studio-pluginhost'], { CARGO_TARGET_DIR: target });
  run('cargo', ['test', '--manifest-path', path.join(root, 'engine', 'Cargo.toml'), '-p', 'krypt-studio-pluginclient', '-p', 'krypt-studio-pluginhost'], {
    CARGO_TARGET_DIR: target,
    KRYPT_PLUGINHOST: path.join(target, 'debug', 'krypt-studio-pluginhost.exe'),
    KRYPT_TEST_CLAP: path.join(out, 'CLAP', 'krypt-test.clap'),
    KRYPT_TEST_VST3: path.join(out, 'VST3', 'KryptTestGainBundle.vst3'),
  });
}
